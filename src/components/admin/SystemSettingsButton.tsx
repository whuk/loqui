import { isAdmin } from '@/lib/adminService';

interface SystemSettingsButtonProps {
    isAdmin?: boolean;
}

export function SystemSettingsButton({ isAdmin: isAdminProp }: SystemSettingsButtonProps) {
    const shouldShow = isAdmin({ isAdmin: isAdminProp });

    if (!shouldShow) {
        return null;
    }

    const handleClick = () => {
        window.open('/admin/settings', '_blank');
    };

    return (
        <button
            type="button"
            aria-label="시스템 설정"
            onClick={handleClick}
            className="flex items-center gap-2 px-3 py-2 text-sm rounded-lg hover:bg-[var(--bg-tertiary)] transition-colors"
        >
            <AdminSettingsIcon />
            <span>시스템 설정</span>
        </button>
    );
}

